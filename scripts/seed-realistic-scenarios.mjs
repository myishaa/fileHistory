async function login() {
  const response = await fetch(`${API_BASE_URL}/api/auth/login`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ username, password }),
  });
  const body = await response.json().catch(() => undefined);
  if (!response.ok) throw new Error(`Login failed: ${body?.error ?? response.status}`);
  const match = (response.headers.get("set-cookie") ?? "").match(/recordkeeper_session=([^;]+)/);
  if (!match) throw new Error("Login did not return a session cookie.");
  return decodeURIComponent(match[1]);
}

async function api(path, token, options = {}) {
  const response = await fetch(`${API_BASE_URL}${path}`, {
    ...options,
    headers: {
      cookie: `recordkeeper_session=${encodeURIComponent(token)}`,
      ...(options.body ? { "content-type": "application/json" } : {}),
      ...(options.headers ?? {}),
    },
  });
  const body = await response.json().catch(() => undefined);
  if (!response.ok) {
    throw new Error(`${options.method ?? "GET"} ${path}: ${body?.error ?? response.status}`);
  }
  return body;
}

