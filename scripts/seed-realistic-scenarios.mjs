async function ensureNoCollision(definition, token) {
  const params = new URLSearchParams({
    selectedYear: "__all_files__",
    freeText: definition.code,
    page: "1",
    pageSize: "50",
  });
  const result = await api(`/api/files/search?${params}`, token);
  const exact = (result.files ?? []).find((file) => file.uniqueCode === definition.code);
  if (exact)
    throw new Error(`Unique code ${definition.code} already exists (${exact.fileNo ?? exact.id}).`);
}

async function main() {
  const token = await login();
  const created = [];
  try {
    for (const definition of definitions) await ensureNoCollision(definition, token);
    for (const definition of definitions) {
      const payload = baseFile(definition);
      const result = await api("/api/files", token, {
        method: "POST",
        body: JSON.stringify(payload),
      });
      created.push({
        id: result.file.id,
        uniqueCode: result.file.uniqueCode,
        year: result.file.year,
        fileType: result.file.fileType,
        fileNo: result.file.fileNo,
      });
      console.log(`Created ${result.file.uniqueCode}: ${definition.title}`);
    }
  } finally {
    await fetch(`${API_BASE_URL}/api/auth/logout`, {
      method: "POST",
      headers: { cookie: `recordkeeper_session=${encodeURIComponent(token)}` },
    }).catch(() => undefined);
  }
  console.log(JSON.stringify({ created: created.length, files: created }, null, 2));
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
